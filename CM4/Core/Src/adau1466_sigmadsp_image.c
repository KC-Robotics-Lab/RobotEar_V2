static HAL_StatusTypeDef adau1466_write_block(I2C_HandleTypeDef *hi2c,
                                                uint16_t device_address_8bit,
                                                uint16_t subaddress,
                                                const uint8_t *data,
                                                uint16_t length)
{
    if ((hi2c == NULL) || (data == NULL) || (length == 0U))
    {
        g_adau1466_sigma_last_address = subaddress;
        g_adau1466_sigma_last_status = HAL_ERROR;
        return HAL_ERROR;
    }

    g_adau1466_sigma_last_address = subaddress;
    g_adau1466_sigma_last_status =
        HAL_I2C_Mem_Write(hi2c,
                          device_address_8bit,
                          subaddress,
                          I2C_MEMADD_SIZE_16BIT,
                          (uint8_t *)(uintptr_t)data,
                          length,
                          ADAU1466_SIGMA_I2C_TIMEOUT_MS);

    return g_adau1466_sigma_last_status;
}

static HAL_StatusTypeDef adau1466_write_u16(I2C_HandleTypeDef *hi2c,
                                            uint16_t device_address_8bit,
                                            uint16_t subaddress,
                                            uint16_t value)
{
    const uint8_t bytes[2] =
    {
        (uint8_t)((value >> 8) & 0xFFU),
        (uint8_t)(value & 0xFFU)
    };

    return adau1466_write_block(hi2c,
                                device_address_8bit,
                                subaddress,
                                bytes,
                                (uint16_t)sizeof(bytes));
}

